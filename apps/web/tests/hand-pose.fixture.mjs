export function handLandmarks({ side = 'left', x = 0.5, y = 0.5, pinching = false } = {}) {
  const points = [
    [0, 0.18], [-0.055, 0.12], [-0.10, 0.06], [-0.14, 0], [-0.17, -0.05],
    [-0.06, -0.005], [-0.07, -0.11], [-0.07, -0.19], [-0.07, -0.25],
    [0, -0.02], [0, -0.14], [0, -0.23], [0, -0.29],
    [0.06, -0.005], [0.07, -0.12], [0.08, -0.21], [0.08, -0.26],
    [0.11, 0.025], [0.14, -0.06], [0.16, -0.12], [0.18, -0.17],
  ];
  if (pinching) {
    points[3] = [-0.12, 0.04]; points[4] = [-0.14, -0.02];
    points[7] = [-0.13, -0.08]; points[8] = [-0.13, -0.02];
  }
  return points.map(([dx, dy]) => [x + dx * (side === 'left' ? 1 : -1), y + dy, 0]);
}
