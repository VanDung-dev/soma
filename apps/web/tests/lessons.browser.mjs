import { createLesson, lessonBody, savedLesson, saveLessonDraft, selectLessonModel } from './lesson-editor-tools.mjs';
import assert from 'node:assert/strict';
import { checkLessonReader } from './lesson-reader.browser.mjs';
import { checkLessonScenes } from './lesson-scenes.browser.mjs';
import { checkLessonEditorLayout, checkLessonResponsiveLayout } from './lesson-editor-layout.browser.mjs';
import { checkLessonRichText } from './lesson-rich-text.browser.mjs';
import { checkLessonOutlineTouch } from './lesson-outline-touch.browser.mjs';
import { checkLessonImages } from './lesson-images.browser.mjs';
import { checkLessonEditorExperience } from './lesson-editor-experience.browser.mjs';
import { checkLessonQuestions, checkLessonImageProgress } from './lesson-questions.browser.mjs';
import { checkLessonCanvas } from './lesson-canvas.browser.mjs';
import { checkLessonBackground } from './lesson-background.browser.mjs';
import { checkLessonPlayerBackground } from './lesson-player-background.browser.mjs';
import { checkLessonBackgroundStability } from './lesson-background-stability.browser.mjs';
import { checkLessonPlayerExit } from './lesson-player-exit.browser.mjs';
import { checkLessonModelRemoval } from './lesson-model-removal.browser.mjs';
import { checkLessonCorruptStorage } from './lesson-corrupt-storage.browser.mjs';
import { checkLessonOutlineDelete } from './lesson-outline-delete.browser.mjs';

export async function checkLessons(page) {
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/home');
  await page.locator('.home-module-lessons').click();
  await page.getByRole('status').filter({ hasText: 'Chưa có bài học' }).waitFor();
  await createLesson(page);
  const editorUrl = page.url();
  assert.match(editorUrl, /\/lessons\/[a-z0-9]+\/edit$/);
  const created = await savedLesson(page);
  assert(Number.isSafeInteger(created.createdAt));
  assert.equal(created.updatedAt, created.createdAt);
  await page.getByRole('button', { name: 'Xem trước', exact: true }).click();
  await page.getByText('Nội dung của mục sẽ xuất hiện ở đây khi bạn soạn bài.', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('soma.lesson-v1:' + location.pathname.split('/')[2])).steps.length), 0);
  await page.getByRole('button', { name: 'Tiếp tục soạn bài', exact: true }).click();

  await page.getByLabel('Tên bài học').fill('Bài kiểm thử');
  const editorOutline = page.locator('#lesson-author-outline');
  const sectionHeading = editorOutline.locator('.lesson-outline-details + .lesson-outline-section-heading');
  await sectionHeading.getByRole('heading', { name: 'Danh sách mục', exact: true }).waitFor();
  await sectionHeading.getByRole('button', { name: 'Thêm mục', exact: true }).click();
  await page.getByLabel('Tên mục').fill('Đọc phần mở đầu');
  assert.equal(await editorOutline.locator('.lesson-block-icon').count(), 0);
  await page.getByLabel('Hiển thị mô hình 3D ở mục này', { exact: true }).uncheck();
  await lessonBody(page).fill('Quan sát phần mô tả.');
  await saveLessonDraft(page);
  const saved = await savedLesson(page);
  assert.equal(saved.createdAt, created.createdAt);
  assert(saved.updatedAt > created.updatedAt);
  const visibleTimestamps = process.env.VITE_DEBUG_LESSON_TIMESTAMPS === '1'
    ? [saved.createdAt, saved.updatedAt].map(value => new Date(value).toISOString())
    : [];
  const timestampsIn = root => root.locator('.lesson-timestamps time').evaluateAll(times => times.map(time => time.dateTime));
  assert.deepEqual(await timestampsIn(page.locator('.lesson-editor')), visibleTimestamps);
  await page.getByRole('button', { name: 'Xem trước' }).click();
  await page.getByRole('heading', { name: 'Đọc phần mở đầu' }).waitFor();
  assert.deepEqual(await timestampsIn(page.locator('.lesson-player')), visibleTimestamps);
  await page.locator('.lesson-player .lesson-model').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.lesson-player > .model-canvas').count(), 1);
  await page.getByRole('button', { name: 'Hoàn thành', exact: true }).click();
  await page.getByRole('heading', { name: 'Đã hoàn thành bài học' }).waitFor();

  await page.reload();
  assert.equal(page.url(), editorUrl);
  await page.getByRole('button', { name: 'Thoát', exact: true }).click();
  const savedCard = page.locator('.lesson-card').filter({ hasText: 'Bài kiểm thử' });
  await savedCard.waitFor();
  assert.deepEqual(await timestampsIn(savedCard), visibleTimestamps);
  const librarySearch = page.getByRole('searchbox', { name: 'Tìm bài học' });
  await librarySearch.fill('khong ton tai');
  await page.getByRole('status').filter({ hasText: 'Không tìm thấy bài học' }).waitFor();
  await librarySearch.fill('bai kiem thu');
  await page.getByRole('button', { name: 'Chỉnh sửa' }).click();
  assert.equal(page.url(), editorUrl);
  await page.locator('#lesson-author-outline .lesson-outline-row').filter({ hasText: 'Đọc phần mở đầu' }).click();
  assert.equal(await page.getByLabel('Tên mục').inputValue(), 'Đọc phần mở đầu');

  await page.locator('#lesson-author-outline').getByRole('button', { name: 'Thêm mục', exact: true }).click();
  const incomplete = await savedLesson(page);
  await page.getByRole('button', { name: 'Xem trước', exact: true }).click();
  await page.getByRole('heading', { name: 'Mục chưa đặt tên', exact: true }).waitFor();
  assert(await page.locator('.lesson-preview-issue').isVisible(), 'Preview highlights the unfinished section');
  await page.getByRole('button', { name: 'Quay lại soạn bài', exact: true }).click();
  assert.deepEqual(await savedLesson(page), incomplete);
  const compose = page.getByRole('button', { name: 'Thiết lập 3D', exact: true });
  assert.equal(await page.locator('#lesson-author-inspector').count(), 0);
  await selectLessonModel(page, 'collection:cc46df69f8495544');
  assert(await compose.isEnabled());
  await compose.click();
  const scene = page.locator('.lesson-model-settings[data-open="true"]');
  const sceneCount = scene.locator('.lesson-scene-tree').getByRole('status').filter({ hasText: /\d+ cấu trúc trong mục này/ });
  const modelCount = Number.parseInt(await sceneCount.textContent(), 10);
  assert(modelCount > 0);
  await page.keyboard.press('Escape');
  const search = page.locator('.structure-search-popover:popover-open');
  const frame = page.locator('.lesson-scene-region');
  await frame.locator('.orientation-axes [data-axis="Y"][data-direction="1"]').waitFor();
  const explode = frame.getByRole('slider', { name: 'Mức độ tách' });
  await explode.and(frame.locator('input:enabled')).waitFor();
  await explode.focus();
  await explode.press('End');
  assert.equal(await explode.inputValue(), '100');
  await explode.press('Home');
  assert.equal(await explode.inputValue(), '0');
  await frame.getByRole('button', { name: 'Tìm kiếm', exact: true }).click();
  await search.getByRole('combobox').fill('optic nerve');
  await search.locator('[role="option"][data-structure-id]').first().click();
  const part = frame.getByRole('region', { name: 'Thông tin bộ phận' });
  await part.getByRole('heading').waitFor();
  const isolatePart = part.getByRole('button', { name: 'Xem riêng bộ phận' });
  const isolatePartWidth = (await isolatePart.boundingBox()).width;
  await isolatePart.click();
  const restoreRegion = part.getByRole('button', { name: 'Về vùng bài học' });
  const restoreRegionWidth = (await restoreRegion.boundingBox()).width;
  assert(Math.abs(isolatePartWidth - restoreRegionWidth) < 1, 'Keep isolate and restore actions aligned to the same width');
  await restoreRegion.click();
  await part.getByRole('heading').waitFor();
  assert(await part.isVisible(), 'Keep the selected structure visible after restoring the lesson region');
  const width = await frame.evaluate(node => node.clientWidth);
  await page.locator('#lesson-toggle-outline').click();
  assert(await page.locator('#lesson-author-outline').isHidden());
  assert((await frame.evaluate(node => node.clientWidth)) > width);
  await page.locator('#lesson-toggle-outline').click();
  assert(await page.locator('#lesson-author-outline').isVisible());
  assert(await page.locator('.lesson-step-options').isVisible());
  await page.locator('#lesson-toggle-outline').click();

  await page.setViewportSize({ width: 320, height: 700 });
  assert(await page.locator('.lessons-screen').evaluate(element => element.scrollWidth <= element.clientWidth));
  assert(await explode.evaluate(node => node.closest('fieldset').getBoundingClientRect().width <= 320));
  assert((await frame.locator('.lesson-scene-viewport').boundingBox()).height >= 140, 'Mobile authoring must leave room to inspect the model');
  assert(await page.locator('#lesson-author-outline').isHidden());
  assert(await page.locator('.lesson-step-options').isVisible());
  await compose.click();
  assert.equal(await scene.locator('.lesson-system-checkbox').count(), 9);
  assert(await scene.evaluate(node => node.scrollWidth <= node.clientWidth));
  await scene.locator('.lesson-scene-tree').getByRole('button', { name: 'Ẩn tất cả', exact: true }).click();
  await scene.getByRole('status').filter({ hasText: '0 cấu trúc' }).waitFor();
  await scene.getByRole('button', { name: 'Về nhóm ban đầu', exact: true }).click();
  await scene.getByRole('status').filter({ hasText: `${modelCount} cấu trúc` }).waitFor();
  await scene.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await scene.waitFor({ state: 'hidden' });
  await saveLessonDraft(page);
  const saved = await savedLesson(page);
  assert.equal(saved.steps[1].visibleIds.length, modelCount);
  assert.equal(saved.steps[1].targetId, 'collection:cc46df69f8495544');
  const model = scene.getByRole('listbox', { name: 'Mô hình 3D của bài học' });
  const confirm = page.getByRole('dialog', { name: 'Xác nhận' });
  await compose.click();
  await model.selectOption('collection:baf3076d0495a617');
  await scene.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await confirm.getByRole('button', { name: 'Hủy', exact: true }).click();
  assert.deepEqual(await savedLesson(page), saved);
  await scene.getByRole('button', { name: 'Áp dụng', exact: true }).click();
  await confirm.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
  await scene.waitFor({ state: 'hidden' });
  await frame.locator('.model-canvas[aria-busy="false"]').waitFor();
  await saveLessonDraft(page);
  const revised = await savedLesson(page);
  assert.equal(revised.steps[1].targetId, 'collection:baf3076d0495a617');
  assert.deepEqual(revised.steps[0], saved.steps[0]);
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.locator('#lesson-toggle-outline').click();
  await page.locator('#lesson-author-outline').getByRole('button', { name: 'Thêm mục', exact: true }).click();
  await frame.getByRole('button', { name: 'Sao chép cảnh mục trước', exact: true }).click();
  await frame.locator('.model-canvas[aria-busy="false"]').waitFor();
  await saveLessonDraft(page);
  const added = await savedLesson(page);
  assert.equal(added.steps[2].targetId, revised.steps[1].targetId);
  assert(await compose.isEnabled());
  for (const check of [checkLessonResponsiveLayout, checkLessonPlayerExit, checkLessonBackgroundStability, checkLessonPlayerBackground, checkLessonBackground, checkLessonCanvas, checkLessonReader, checkLessonScenes, checkLessonEditorLayout, checkLessonRichText,
    checkLessonOutlineTouch, checkLessonOutlineDelete, checkLessonEditorExperience, checkLessonQuestions, checkLessonImageProgress, checkLessonImages, checkLessonModelRemoval, checkLessonCorruptStorage]) {
    console.log(check.name);
    await check(page);
  }
}
